// Writes packages/sim/src/version.generated.ts with SIM_VERSION, a hash of the sim and
// content sources. Two clients can share a valley only with the same SIM_VERSION.
// Runs before typecheck, test, build, dev, bench and e2e (see the root package.json).
import { createHash } from 'node:crypto';
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('../../..', import.meta.url));
const sources = ['packages/sim/src', 'packages/content/src'];
const out = join(root, 'packages/sim/src/version.generated.ts');

function walk(dir) {
  const files = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) files.push(...walk(full));
    else if (/\.(ts|json)$/.test(entry.name) && !/\.(test|generated)\.ts$/.test(entry.name)) files.push(full);
  }
  return files;
}

const hash = createHash('sha256');
for (const dir of sources) {
  for (const file of walk(join(root, dir)).sort()) {
    // Normalize line endings so every checkout produces the same version.
    const text = readFileSync(file, 'utf8').replace(/\r\n/g, '\n');
    hash.update(relative(root, file).split('\\').join('/'));
    hash.update('\0');
    hash.update(text);
    hash.update('\0');
  }
}

const version = hash.digest('hex').slice(0, 12);
const body = `// Generated by packages/sim/scripts/gen-version.mjs. Do not edit; gitignored.\nexport const SIM_VERSION = '${version}';\n`;
if (!existsSync(out) || readFileSync(out, 'utf8') !== body) writeFileSync(out, body);
console.log(`simVersion ${version}`);
