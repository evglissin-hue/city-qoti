// Fetches the CC0 recordings in manifest.json, checks each hash, trims, normalizes loudness and
// transcodes them to AAC with ffmpeg, then writes apps/client/public/audio/CREDITS.md from the
// manifest (C5G). `npm run audio:fetch`. The game's own sounds are synthesized; this pipeline is for
// recordings added later, and it refuses anything that is not CC0 or public domain.
import { createHash } from 'node:crypto';
import { execFileSync } from 'node:child_process';
import { mkdirSync, mkdtempSync, readFileSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..', '..');
const out = join(root, 'apps', 'client', 'public', 'audio');
const manifest = JSON.parse(readFileSync(join(here, 'manifest.json'), 'utf8'));
const LICENSES = new Set(['CC0-1.0', 'PD']);
const LOUDNESS = { music: -18, ambience: -22, effect: -16 };
const BITRATE = { music: ['2', '96k'], ambience: ['1', '64k'], effect: ['1', '64k'] };

mkdirSync(out, { recursive: true });
const work = mkdtempSync(join(tmpdir(), 'qoti-audio-'));
for (const f of manifest.files) {
  if (!LICENSES.has(f.license)) throw new Error(`${f.id}: license ${f.license} is not CC0 or public domain`);
  const res = await fetch(f.url);
  if (!res.ok) throw new Error(`${f.id}: ${res.status} from ${f.url}`);
  const bytes = Buffer.from(await res.arrayBuffer());
  const sha = createHash('sha256').update(bytes).digest('hex');
  if (sha !== f.sha256) throw new Error(`${f.id}: sha256 ${sha} does not match the manifest`);
  const src = join(work, `${f.id}.src`);
  writeFileSync(src, bytes);
  const [channels, bitrate] = BITRATE[f.kind];
  const trim = f.trim ? ['-ss', String(f.trim[0]), '-to', String(f.trim[1])] : [];
  execFileSync('ffmpeg', [
    '-y',
    '-loglevel',
    'error',
    ...trim,
    '-i',
    src,
    '-af',
    `loudnorm=I=${LOUDNESS[f.kind]}:TP=-1.5`,
    '-ac',
    channels,
    '-c:a',
    'aac',
    '-b:a',
    bitrate,
    join(out, `${f.id}.m4a`),
  ]);
  console.log(`ok ${f.id}`);
}

const lines = manifest.files.map((f) => `- \`${f.id}.m4a\`: ${f.author}, ${f.license}, ${f.source}`);
writeFileSync(
  join(out, 'CREDITS.md'),
  [
    '# Sound credits',
    '',
    'Generated by `npm run audio:fetch` from `tools/audio/manifest.json`; do not edit by hand.',
    '',
    'The music, ambience and effects are synthesized in the browser as the game plays (`apps/client/src/audio/synth`), so they have no recordings to credit.',
    ...(lines.length ? ['', 'Recordings (CC0 or public domain):', '', ...lines] : []),
    '',
  ].join('\n'),
);
console.log(`${manifest.files.length} recordings, credits written`);
